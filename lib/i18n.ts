export function translate(source: string, locale: Locale): string {
  if (locale === 'en') return source;
  const key = source.replace(/\s+/g, ' ').trim();
  let result = Object.hasOwn(russian, key) ? russian[key] : undefined;
  if (!result) {
    result = key
      .replace(/^([\d, ]+) tasks submitted$/, 'Отправлено задач: $1')
      .replace(/^(\d+) tasks$/, '$1 задач')
      .replace(/^View task (.+)$/, 'Открыть задачу $1')
      .replace(/^Revoke (.+)$/, 'Отозвать $1')
      .replace(
        /^Daily solutions chart\. (\d+) solved and (\d+) failed tasks in this period\.$/,
        'График решений по дням. За период успешно: $1, с ошибкой: $2.',
      )
      .replace(/^(\d+(?:\.\d+)?)s$/, '$1 с');
  }
  return (source.match(/^\s+/)?.[0] ? ' ' : '') + result + (source.match(/\s+$/)?.[0] ? ' ' : '');
}
